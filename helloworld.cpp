#include <iostream> //Header file that contains functions for basic input/ output operations
//using namespace std; //Can use names for variables and objects from standard library

int main(){
    //standard = std, character output = cout
    std::cout << "I like pasta" << '\t'; // '\t' creates tab
    std::cout << "I also like chinese food! \n"; //'\n' also ends line
    std::cout << "This is a new line" << std::endl; //endl = end line
    std::cout << "This is a backslash \\ "<< "\" This creates a double quote\"";
    return 0;
}